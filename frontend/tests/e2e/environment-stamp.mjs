import assert from 'node:assert/strict'
import { join } from 'node:path'
import { expect } from '@playwright/test'

export async function checkEnvironmentStamps(page, application, output) {
  await application.evaluate(({ BaseWindow }) => BaseWindow.getAllWindows()[0].setSize(1440, 1000))
  const names = ['Anker（合成测试）', '上海元辰云谷（合成）', '深圳启畅（合成）', '北京临场（合成）']
  await page.evaluate(async names => {
    const library = await window.copilot.getInterviewLibrary()
    const current = library.environments.find(value => value.id === library.activeEnvironmentId)
    await window.copilot.saveEnvironment({ ...current, name: names[0] })
    for (const name of names.slice(1)) await window.copilot.saveEnvironment({ name, interviewType: 'technical', resumeId: library.resumes[0].id, targetId: null, referenceIds: [] })
  }, names)
  for (const name of names) await expect(page.getByRole('button', { name: `加印章 ${name}` })).toBeVisible()
  const stamps = [['一面中', '蓝色'], ['等待二面中', '橙色'], ['已下 offer', '绿色'], ['已挂', '红色']]
  for (let index = 0; index < names.length; index++) {
    await page.getByRole('button', { name: `加印章 ${names[index]}` }).click()
    await page.getByRole('button', { name: stamps[index][0], exact: true }).click()
    await page.getByRole('button', { name: stamps[index][1], exact: true }).click()
    await page.getByRole('button', { name: '保存印章', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '个性化印章' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: `编辑印章 ${names[index]}：${stamps[index][0]}` })).toBeVisible()
  }
  await expect(page.getByText('印章已保存', { exact: true })).toHaveCount(0, { timeout: 10000 })
  await page.screenshot({ path: join(output, 'environment-stamp-wide.png') })
  const first = page.getByRole('button', { name: `编辑印章 ${names[0]}：一面中` })
  await first.focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog', { name: '个性化印章' })).toBeVisible()
  await page.screenshot({ path: join(output, 'environment-stamp-editor.png') })
  await page.keyboard.press('Escape'); await expect(first).toBeFocused()
  await first.click()
  await page.getByRole('button', { name: '删除常用文案 已挂', exact: true }).click()
  await expect(page.getByRole('button', { name: '已挂', exact: true })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: '印章文字' })).toHaveValue('一面中')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: `编辑印章 ${names[0]}：一面中` }).click()
  await expect(page.getByRole('button', { name: '已挂', exact: true })).toHaveCount(0)
  await page.screenshot({ path: join(output, 'environment-stamp-shortcut-deleted.png') })
  await page.getByRole('button', { name: '恢复默认', exact: true }).click()
  await expect(page.getByRole('button', { name: '已挂', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  // A real concurrent server mutation produces409 while the existing dialog preserves its draft.
  await first.click()
  await page.evaluate(async () => {
    const library = await window.copilot.getInterviewLibrary(), value = library.environments.find(environment => environment.id === library.activeEnvironmentId)
    await window.copilot.saveEnvironmentStamp({ id: value.id, version: value.version, stamp: { text: '等通知', color: 'amber' } })
  })
  await page.getByRole('textbox', { name: '印章文字' }).fill('准备复试')
  await page.getByRole('button', { name: '保存印章', exact: true }).click()
  await expect(page.getByText(/请刷新环境后重试/).last()).toBeVisible()
  await expect(page.getByRole('textbox', { name: '印章文字' })).toHaveValue('准备复试')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: `编辑印章 ${names[0]}：等通知` }).click()
  await page.getByRole('textbox', { name: '印章文字' }).fill('😀'.repeat(8))
  await page.getByRole('button', { name: '保存印章', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '个性化印章' })).toHaveCount(0)
  await expect(page.getByText('印章已保存', { exact: true })).toHaveCount(0, { timeout: 10000 })
  await expect(page.getByText(/请刷新环境后重试/)).toHaveCount(0, { timeout: 10000 })
  await application.evaluate(({ BaseWindow }) => { const window = BaseWindow.getAllWindows()[0]; window.setMinimumSize(380, 560); window.setSize(448, 1000) })
  await expect.poll(() => page.evaluate(() => innerWidth)).toBe(448)
  const article = page.getByRole('article', { name: `面试环境 ${names[0]}` })
  const before = await article.boundingBox()
  assert.ok(before)
  await application.evaluate(({ BaseWindow }, difference) => {
    const window = BaseWindow.getAllWindows()[0], bounds = window.getBounds()
    window.setSize(Math.round(bounds.width + difference), bounds.height)
  }, 320 - before.width)
  await expect.poll(async () => Math.round((await article.boundingBox()).width)).toBe(320)
  await article.scrollIntoViewIfNeeded()
  const card = await article.boundingBox(), stamp = await article.getByRole('button', { name: /编辑印章/ }).boundingBox(), resources = await article.locator('dl').boundingBox(), actions = await article.getByRole('button', { name: '开始面试', exact: true }).boundingBox()
  assert.ok(card && stamp && resources && actions)
  assert.ok(Math.abs(card.width - 320) <= 2, `Card width ${card.width}`)
  assert.ok(stamp.y + stamp.height <= resources.y, 'Stamp overlaps resource text')
  const type = await article.getByText('技术面试', { exact: true }).boundingBox()
  assert.ok(type && stamp.x >= type.x + type.width, 'Stamp overlaps interview type')
  assert.ok(stamp.y + stamp.height <= actions.y, 'Stamp overlaps actions')
  assert.ok(stamp.x >= card.x && stamp.x + stamp.width <= card.x + card.width, 'Stamp overflows narrow card')
  await article.screenshot({ path: join(output, 'environment-stamp-card-320.png') })
  await article.getByRole('button', { name: /编辑印章/ }).click()
  const preview = page.getByLabel('印章预览 ' + '😀'.repeat(8))
  const emojiBox = await preview.boundingBox(), previewSurface = await page.getByLabel('印章实时预览').boundingBox()
  assert.ok(emojiBox && previewSurface && emojiBox.width <= previewSurface.width && emojiBox.height <= previewSurface.height)
  await page.screenshot({ path: join(output, 'environment-stamp-editor-narrow-emoji.png') })
  await page.getByRole('textbox', { name: '印章文字' }).fill('正在等待第二轮中')
  const chineseBox = await page.getByLabel('印章预览 正在等待第二轮中').boundingBox()
  assert.ok(chineseBox && chineseBox.width <= previewSurface.width && chineseBox.height <= previewSurface.height)
  await page.screenshot({ path: join(output, 'environment-stamp-editor-narrow-chinese.png') })
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.screenshot({ path: join(output, 'environment-stamp-narrow.png') })
  // Ordinary save strips stamp from its payload; the server preserves it.
  const resolved = await page.evaluate(async () => {
    let library = await window.copilot.getInterviewLibrary(), value = library.environments.find(environment => environment.id === library.activeEnvironmentId)
    library = await window.copilot.saveEnvironment(value)
    return library.environments.find(environment => environment.id === library.activeEnvironmentId)
  })
  assert.equal(resolved.stamp.text, '😀'.repeat(8))
  // The preceding mutation intentionally bypassed the UI save handler; reload its fresh version before starting.
  await page.reload()
  await page.evaluate(() => window.copilot.getSettings())
  await expect(page.getByRole('button', { name: `编辑印章 ${names[0]}：` + '😀'.repeat(8) })).toBeVisible()
  await application.evaluate(({ BaseWindow }) => BaseWindow.getAllWindows()[0].setSize(1440, 1000))
  await article.getByRole('button', { name: '开始面试', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '当前问题' })).toBeVisible()
  await page.getByRole('button', { name: '准备面试', exact: true }).click()
  await expect(article.getByRole('button', { name: `编辑环境 ${names[0]}` })).toBeDisabled()
  const stateBefore = await page.evaluate(async () => ({ wallet: await window.copilot.getWallet(), snapshot: (await window.copilot.getSettings()).interviewEnvironment }))
  await article.getByRole('button', { name: /编辑印章/ }).click()
  await page.getByRole('button', { name: '清除印章', exact: true }).click()
  await expect(article.getByRole('button', { name: `加印章 ${names[0]}` })).toBeVisible()
  const stateAfter = await page.evaluate(async () => ({ wallet: await window.copilot.getWallet(), snapshot: (await window.copilot.getSettings()).interviewEnvironment }))
  assert.equal(stateAfter.wallet.session.status, 'active')
  assert.equal(stateAfter.wallet.session.id, stateBefore.wallet.session.id)
  assert.deepEqual(stateAfter.snapshot, stateBefore.snapshot)
  assert.equal(Object.hasOwn(stateAfter.snapshot, 'stamp'), false)
  await expect(page.getByText('印章已清除', { exact: true })).toHaveCount(0, { timeout: 10000 })
  await page.screenshot({ path: join(output, 'environment-stamp-active-clear.png') })
  await page.getByRole('button', { name: '工作台', exact: true }).click()
  await page.getByRole('button', { name: '结束面试', exact: true }).click()
  return ['four explicit user-selected stamps persist through real IPC and Java', 'shortcut removal persists after reload, preserves current stamp, and restores defaults', 'keyboard editing and real409 preserve draft', '8-codepoint emoji stamp fits320px without overlapping text/actions', 'ordinary save preserves stamp', 'active interview survives stamp clear with identical background snapshot']
}
