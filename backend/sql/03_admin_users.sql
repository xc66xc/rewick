-- Existing accounts remain ordinary users. NULL quota overrides inherit deployment limits.
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS role VARCHAR(16) NOT NULL DEFAULT 'USER'
    CHECK (role IN ('USER', 'ADMIN'));
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS daily_answers INTEGER
    CHECK (daily_answers BETWEEN 0 AND 1000000);
ALTER TABLE app_users ADD COLUMN IF NOT EXISTS daily_knowledge_queries INTEGER
    CHECK (daily_knowledge_queries BETWEEN 0 AND 1000000);
CREATE INDEX IF NOT EXISTS app_users_admin_idx ON app_users(id) WHERE role = 'ADMIN' AND is_enabled = TRUE;

ALTER TABLE usage_events ADD COLUMN IF NOT EXISTS model VARCHAR(256) NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS usage_events_filter_idx ON usage_events(capability, model, status, id DESC);

CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_app_users_id BIGINT NOT NULL REFERENCES app_users(id),
    action VARCHAR(64) NOT NULL,
    target VARCHAR(160) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS audit_events_actor_idx ON audit_events(actor_app_users_id, id DESC);
