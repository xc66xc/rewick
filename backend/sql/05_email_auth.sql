-- Optional verified identities do not bind or modify existing username accounts.
CREATE TABLE IF NOT EXISTS auth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_users_id BIGINT NOT NULL REFERENCES app_users(id),
    identity_type VARCHAR(32) NOT NULL,
    identifier VARCHAR(254) NOT NULL,
    verified_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(identity_type, identifier),
    UNIQUE(app_users_id, identity_type)
);

CREATE TABLE IF NOT EXISTS email_verifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    code_digest VARCHAR(64) NOT NULL DEFAULT '',
    nonce VARCHAR(32) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'empty'
        CHECK (status IN ('empty', 'pending', 'ready', 'failed', 'consumed')),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_send_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    send_count INTEGER NOT NULL DEFAULT 0 CHECK (send_count >= 0),
    failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS email_verifications_expiry_idx ON email_verifications(expires_at);

CREATE TABLE IF NOT EXISTS email_config (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    host VARCHAR(253) NOT NULL DEFAULT '',
    port INTEGER NOT NULL DEFAULT 587 CHECK (port BETWEEN 1 AND 65535),
    username VARCHAR(254) NOT NULL DEFAULT '',
    encrypted_password VARCHAR(32768) NOT NULL DEFAULT '',
    from_address VARCHAR(254) NOT NULL DEFAULT '',
    is_start_tls BOOLEAN NOT NULL DEFAULT TRUE,
    is_ssl BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO email_config(id) VALUES (1) ON CONFLICT (id) DO NOTHING;
