CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE auth_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_users_id BIGINT NOT NULL REFERENCES app_users(id),
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    is_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX auth_tokens_user_idx ON auth_tokens(app_users_id);
CREATE INDEX auth_tokens_expiry_idx ON auth_tokens(expires_at);

CREATE TABLE usage_daily (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_users_id BIGINT NOT NULL REFERENCES app_users(id),
    usage_day DATE NOT NULL,
    capability VARCHAR(16) NOT NULL CHECK (capability IN ('llm', 'knowledge', 'asr')),
    used_count INTEGER NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(app_users_id, usage_day, capability)
);

CREATE TABLE usage_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_users_id BIGINT NOT NULL REFERENCES app_users(id),
    request_id VARCHAR(128) NOT NULL,
    capability VARCHAR(16) NOT NULL CHECK (capability IN ('llm', 'knowledge', 'asr')),
    status VARCHAR(16) NOT NULL DEFAULT 'started'
        CHECK (status IN ('started', 'complete', 'failed', 'cancelled', 'expired')),
    expires_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(app_users_id, request_id, capability)
);
CREATE INDEX usage_events_active_idx ON usage_events(app_users_id, capability, expires_at) WHERE status = 'started';
CREATE INDEX usage_events_history_idx ON usage_events(app_users_id, created_at DESC);
